// Bakes the show for hexapod_show.ino from the same kinematics as hexapod.html (hexapod.js):
// the stand and sit poses, one walk cycle, one turn cycle, the wave and the dance, as servo
// angles in wire order, 25 frames a second. Run: node hexapod_show/make_show.mjs
import { writeFileSync } from 'node:fs';
import { DEFAULT_DIMS, LEG_ORDERS, legMounts, homeFeet, legIK, toBody, servoAngles, sitSpread, calibrateFromStand, makeGait } from '../hexapod.js';

// the page's defaults: the robot's own standing angles, tibias reversed, legs numbered round the body
const STAND_REF = [55, 105, 60, 60, 110, 95, 65, 110, 80, 60, 120, 155, 40, 95, 60, 40, 95, 60];
const dims = { ...DEFAULT_DIMS };
const cal = { stand: [...STAND_REF], invert: Array.from({ length: 18 }, (_, i) => i % 3 === 2) };
const order = LEG_ORDERS['around-right'].order;
const first = calibrateFromStand(dims, cal.stand, cal.invert);
cal.trim = first.trim;
// lighter than the page: slower steps, lower feet, slower walk (the robot hangs in the air on a stand)
const ui = { height: first.height, spread: first.spread, speed: 40, lift: 25 };
const PERIOD = 1.2, DT = 0.04;
const mounts = legMounts(dims), sitH = 26;
const SIT_SPREAD = sitSpread(dims, sitH, ui.height, ui.spread);

let clipped = 0, unreach = 0;
function anglesFor(feet, b) {
  const qs = mounts.map((m, i) => { const r = legIK(dims, m, toBody(feet[i], b)); if (!r.ok) unreach++; return r.q; });
  const a = servoAngles(qs, cal, order); if (a.clipped) clipped++;
  return [...a];
}
const body = (h) => ({ h, sx: 0, sy: 0, roll: 0, pitch: 0, yaw: 0 });

// poses
const home = homeFeet(dims, ui.spread), homeSit = homeFeet(dims, SIT_SPREAD);
const STAND = anglesFor(home.map(([x, y]) => [x, y, 0]), body(ui.height));
const SIT = anglesFor(homeSit.map(([x, y]) => [x, y, 0]), body(sitH));

// one steady gait cycle for a command, starting at a half-cycle boundary
function cycle(cmd) {
  const g = makeGait(), out = [];
  for (let k = 0; k < Math.round(4 * PERIOD / DT); k++) g.step(DT, cmd, home, { period: PERIOD, lift: ui.lift });
  for (let k = 0; k < Math.round(PERIOD / DT); k++) { g.step(DT, cmd, home, { period: PERIOD, lift: ui.lift }); out.push(anglesFor(g.feet(home), body(ui.height))); }
  return out;
}
const s = ui.speed / 100;
const WALK = cycle({ vx: 100 * s, vy: 0, wz: 0 });
const TURN = cycle({ vx: 0, vy: 0, wz: 0.45 * s });

// the page's tricks, from the stand pose
function trick(name, dur) {
  const out = [], TAU = 2 * Math.PI;
  for (let t = DT; t <= dur + 1e-9; t += DT) {
    const b = body(ui.height), env = Math.max(0, Math.min(1, t / 0.6, (dur - t) / 0.6));
    const feet = home.map(([x, y]) => [x, y, 0]);
    if (name === 'dance') {
      b.roll = 0.12 * Math.sin(TAU * 0.8 * t) * env; b.pitch = 0.09 * Math.cos(TAU * 0.8 * t) * env;
      b.yaw = 0.15 * Math.sin(TAU * 0.4 * t) * env; b.h += 12 * Math.sin(TAU * 1.6 * t) * env; b.sx = 10 * Math.sin(TAU * 0.8 * t) * env;
    } else {
      const ca = Math.cos(mounts[0].a), sa = Math.sin(mounts[0].a), sw = 28 * Math.sin(TAU * 1.3 * Math.max(0, t - 0.6)) * env;
      b.sx = -18 * ca * env; b.sy = -18 * sa * env;
      feet[0] = [home[0][0] + 30 * ca * env - sw * sa, home[0][1] + 30 * sa * env + sw * ca, 75 * env];
    }
    out.push(anglesFor(feet, b));
  }
  return out;
}
const WAVE = trick('wave', 3.6), DANCE = trick('dance', 6.4);

const same = STAND.every((v, i) => Math.abs(v - STAND_REF[i]) <= 1);
const row = a => '  {' + a.map(v => String(v).padStart(3)).join(',') + '}';
const table = (n, f) => `const uint8_t ${n}[][18] PROGMEM = {\n${f.map(row).join(',\n')}\n};\nconst uint16_t ${n}_N = ${f.length};\n`;
const h = `// Generated by make_show.mjs from hexapod.js (the same kinematics as hexapod.html). Do not edit by hand.
// Stance ${ui.height} mm, spread ${ui.spread}%, walk ${ui.speed}% speed, ${ui.lift} mm steps, ${PERIOD} s cycle, ${Math.round(1 / DT)} frames/s.
#pragma once
const uint8_t FRAME_MS = ${Math.round(DT * 1000)};
const uint8_t STAND[18] PROGMEM = {${STAND.join(', ')}};
const uint8_t SIT[18] PROGMEM = {${SIT.join(', ')}};
${table('WALK', WALK)}${table('TURN', TURN)}${table('WAVE', WAVE)}${table('DANCE', DANCE)}`;
writeFileSync(new URL('./show_data.h', import.meta.url), h);
console.log('stand matches the robot\'s own stand angles:', same, '| stand', STAND.join(','));
console.log('sit', SIT.join(','));
console.log('frames: walk', WALK.length, 'turn', TURN.length, 'wave', WAVE.length, 'dance', DANCE.length, '| clipped frames', clipped, '| unreachable feet', unreach);
const all = [WALK, TURN, WAVE, DANCE].flat(), dmax = [];
for (const F of [WALK, TURN]) { let m = 0; for (let k = 0; k < F.length; k++) { const a = F[k], b = F[(k + 1) % F.length]; for (let i = 0; i < 18; i++) m = Math.max(m, Math.abs(a[i] - b[i])); } dmax.push(m); }
console.log('largest step between frames (deg) walk/turn:', dmax.join('/'), '| per 20 ms:', dmax.map(v => (v / 2).toFixed(1)).join('/'));
let mm = 0; for (let k = 1; k < all.length; k++) for (let i = 0; i < 18; i++) mm = Math.max(mm, Math.abs(all[k][i] - all[k - 1][i]));
